/*
MERGE	:	A MECHANISM TO COMPARE TABLES.	IDENTIFY MATCHING DATA AND MISSING DATA.
			PERFORM DML OPERATIONS ON THIS MATCHING & / MISSING DATA.
			INCREMENTAL CHANGES = INCREMENTAL LOADS.
*/

CREATE TABLE tblOrders  
(
  ID INT NOT NULL PRIMARY KEY,
  TitleTag NVARCHAR(100) NOT NULL,
  Measure INT NOT NULL DEFAULT 0
)

CREATE TABLE tblInventory  
(
  ID INT NOT NULL PRIMARY KEY,
  TitleTag NVARCHAR(100) NOT NULL,
  Measure INT NOT NULL DEFAULT 0
)


