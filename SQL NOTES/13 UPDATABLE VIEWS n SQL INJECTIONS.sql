-- SOLUTION TO ABOVE ERROR:
CREATE TRIGGER trigVwInserts 
ON VW_FLIGHT_RESERVATIONS
INSTEAD OF INSERT
AS
	BEGIN
	DECLARE @CODE VARCHAR(30), @SEATS INT, @CLASS VARCHAR(30) , @SRC VARCHAR(30) , @DEST VARCHAR(30) 

	-- ASSIGN VALUES TO ABOVE VARIABLES
	SELECT @CODE = CRAFT_CODE FROM INSERTED 
	SELECT @SEATS = NO_OF_SEATS FROM INSERTED 
	SELECT @CLASS = CLASS FROM INSERTED 
	SELECT @SRC = SOURCE  FROM INSERTED 
	SELECT @DEST = DESTINATION FROM INSERTED 

	-- DISTRIBUTE THE DATA TO ACTUAL BASE TABLES
	INSERT INTO Reservations VALUES (@CODE, @SEATS, @CLASS) 
	INSERT INTO FLIGHT VALUES (@CODE, @SRC, @DEST) 
	END  


