CREATE DATABASE OnlineReservationsDB

use OnlineReservationsDB

CREATE TABLE RESERVATIONS
(
CRAFT_CODE VARCHAR(30),
NO_OF_SEATS INT,
CLASS VARCHAR(30)
)
GO

CREATE TABLE FLIGHT
(
CRAFT_CODE VARCHAR(30),
SOURCE VARCHAR(30),
DESTINATION VARCHAR(30)
)


CREATE VIEW VW_FLIGHT_RESERVATIONS
AS
SELECT R.CRAFT_CODE,R.NO_OF_SEATS,R.CLASS,
F.SOURCE,F.DESTINATION FROM RESERVATIONS  AS R
JOIN
FLIGHT  AS F
ON
R.CRAFT_CODE = F.CRAFT_CODE


