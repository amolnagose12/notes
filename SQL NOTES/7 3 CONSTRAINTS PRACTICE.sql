-- STEP 1 : DEFINE A DATABASE
CREATE DATABASE UNIVERSITYDATABASEV1

-- STEP 2: CONNECT TO ABOVE DATABASE
USE UNIVERSITYDATABASEV1

-- STEP 3: HOW TO DEFINE "COURSES" TABLE?
CREATE TABLE tblCourses
(
CourseID	INT UNIQUE,				-- THIS COLUMN DOES NOT ALLOW DUPLICATE VALUES
CourseName	VARCHAR(30)	NOT NULL,	-- THIS COLUMN DOES NOT ALLOW NULLS = MANDATORY COLUMN
CourseDur	INT			NULL		-- THIS COLUMN ALLOW NULL VALUES = OPTIONAL COLUMN
)

-- STEP 4: INSERT DATA INTO ABOVE TABLE
