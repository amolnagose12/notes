-- STEP 10: HOW TO DEFINE A "STAFF" TABLE, MAKE IT RELATED TO THE ABOVE "COURSES" TABLE ?
CREATE TABLE tblstaff 
(
StfID	INT	IDENTITY(1001,1) PRIMARY KEY,	-- THIS COLUMN DOES NOT ALLOW DUPLICATES AND DOES NOT ALLOW NULL VALUES
StfName varchar(30) NOT NULL,				-- THIS COLUMN VALUE IS MANDATORY. MEANS, IT DOES NOT ALLOW NULL VALUES
StfAge	tinyint		CHECK(StfAge >= 28),	-- THIS COLUMN VALUE SHOULD BE MINIMUM 28  [RANGE: 0 TO 255]
StfGender char		CHECK(StfGender IN ('M','F')) DEFAULT 'M',	-- THIS COLUMN VALUE SHOULD BE EITHER "M" OR "F"
StfCourseID int		REFERENCES tblcourses(CourseID)  -- THIS EXTRA COLUMN VALUE SHOULD BE FROM THE COURSES TABLES COURSEID COLUMN
)

