SELECT Country,STATE, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
GROUP BY CUBE (Country, STATE)		-- COUNTRY WISE TOTALS + STATE WISE TOTALS + COUNTRY WISE STATE WISE TOTALS + GRAND TOTAL



-- QUERY 12: HOW TO IDENTIFY NEW ROWS RESULTED FROM ROLLUP AND CUBE?
-- SOLUTION : "GROUPING"
SELECT Country, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
GROUP BY ROLLUP(Country)

SELECT Country, SUM(Population) AS TOTAL_POPULATION, GROUPING(Country) FROM tblPopulation
GROUP BY ROLLUP(Country)

SELECT Country, STATE, SUM(Population) AS TOTAL_POPULATION, GROUPING(Country), GROUPING (STATE) FROM tblPopulation
GROUP BY ROLLUP(Country, STATE)


