-- QUERY 5:  HOW TO REPORT TOTAL POPULATION FOR ALL COUNTRIES?
SELECT SUM(Population) AS TOTAL_POPULATION FROM tblPopulation

-- QUERY 6:
--- LETS COMBINE BOTH QUERY #4 AND QUERY #5.
-- MEANS, QUERY TO REPORT COUNTRY WISE TOTAL POPULATION?
-- FOR THIS, WE NEED TO REPORT EACH (UNIQUE) COUNTRY AND ALSO SUM OF POPULATION (AGGREGATION) FOR EACH COUNTRY
SELECT Country, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
