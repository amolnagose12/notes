-- QUERY 8 : HOW TO SPECIFY CONDITIONS ON AGGREGATED DATA?
SELECT Country, STATE, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
GROUP BY Country, State
HAVING SUM(Population) > 15


-- QUERY 9 : HOW TO SPECIFY CONDITIONS ON AGGREGATED DATA AND NON AGGREGATED DATA?
SELECT Country, STATE, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
WHERE STATE = 'STATE1'				-- CONDITIONS ON NON-AGGREGATED DATA. BEFORE GROUP BY
GROUP BY Country, State				-- CONDITIONS ON AGGREGATED DATA. AFTER GROUP BY
HAVING SUM(Population) > 0


-- QUERY 10 : HOW TO REPORT COUNTRY WISE TOTAL POPULATION & GRAND TOTAL POPULATION?
