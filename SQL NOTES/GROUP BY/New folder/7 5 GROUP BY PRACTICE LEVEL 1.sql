-- QUERY 7: HOW TO REPORT COUNTRY WISE, STATE WISE TOTAL POPULATION?
SELECT Country, STATE, SUM(Population) AS TOTAL_POPULATION FROM tblPopulation
GROUP BY Country, State

-- RULE : WHENEVER A QUERY CONTAINS GROUP BY THEN COLUMNS USED IN GROUP BY SHOULD BE USED IN SELECT ALSO. 
